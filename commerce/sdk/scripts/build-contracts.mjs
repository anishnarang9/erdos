// Compiles contracts/*.sol with solc-js into contracts/out/artifacts.json ({ Name: { abi, bytecode } }).
// SIMULATED stub contracts only. Run: pnpm build:contracts
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "contracts");
const outDir = join(srcDir, "out");
const WANTED = ["MockUSDC", "StubCore", "StubProofGate", "MockRiscZeroVerifier"];

const sources = {};
for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".sol")).sort()) {
  sources[file] = { content: readFileSync(join(srcDir, file), "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
for (const e of output.errors ?? []) console.error(e.formattedMessage);
if (errors.length > 0) process.exit(1);

const artifacts = {};
for (const [file, contracts] of Object.entries(output.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!WANTED.includes(name)) continue;
    if (artifacts[name]) throw new Error(`duplicate contract ${name} in ${file}`);
    artifacts[name] = { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` };
  }
}
for (const name of WANTED) if (!artifacts[name]) throw new Error(`missing contract ${name}`);

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "artifacts.json"), `${JSON.stringify(artifacts, null, 2)}\n`);

// Typed `as const` ABIs for viem, generated from the same artifacts.
const abiNames = { StubCore: "stubCoreAbi", StubProofGate: "stubProofGateAbi", MockUSDC: "mockUsdcAbi", MockRiscZeroVerifier: "mockRiscZeroVerifierAbi" };
let ts = "// GENERATED by scripts/build-contracts.mjs from contracts/out/artifacts.json. Do not edit by hand.\n";
ts += "// SIMULATED: stub ABIs until Nick's settlement contracts land. Only this file and contracts/ change when they do.\n\n";
for (const [name, ident] of Object.entries(abiNames)) {
  ts += `export const ${ident} = ${JSON.stringify(artifacts[name].abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "src", "chain", "abi.ts"), ts);
console.log(`solc ${solc.version()} -> contracts/out/artifacts.json, src/chain/abi.ts (${WANTED.join(", ")})`);
